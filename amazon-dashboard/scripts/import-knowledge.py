"""Read-only XLSX importer using Python's standard library. No Excel installation needed."""
from pathlib import Path
from zipfile import ZipFile
from xml.etree import ElementTree as ET
import base64
import hashlib
import json
import posixpath
import re
import sys
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'reference' / '※群爆款更新excel版202610104.xlsx'
N = {'m': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main', 'xdr': 'http://schemas.openxmlformats.org/drawingml/2006/spreadsheetDrawing', 'a': 'http://schemas.openxmlformats.org/drawingml/2006/main'}
REL = '{http://schemas.openxmlformats.org/officeDocument/2006/relationships}'

def cell_text(node):
    return ''.join(part.text or '' for part in node.iter('{' + N['m'] + '}t'))

def resolve(base, target):
    return target.lstrip('/') if target.startswith('/') else posixpath.normpath(posixpath.join(base, target))

with ZipFile(SOURCE) as archive:
    strings = [cell_text(item) for item in ET.fromstring(archive.read('xl/sharedStrings.xml'))] if 'xl/sharedStrings.xml' in archive.namelist() else []
    relations = {r.attrib['Id']: r.attrib['Target'] for r in ET.fromstring(archive.read('xl/_rels/workbook.xml.rels'))}
    image_relations = {r.attrib['Id']: resolve('xl', r.attrib['Target']) for r in ET.fromstring(archive.read('xl/_rels/cellimages.xml.rels'))}
    images = {}
    for picture in ET.fromstring(archive.read('xl/cellimages.xml')).findall('.//xdr:pic', N):
        identifier = picture.find('.//xdr:cNvPr', N).attrib['name']
        relationship = picture.find('.//a:blip', N).attrib[REL + 'embed']
        image_path = image_relations[relationship]
        images[identifier] = 'data:image/png;base64,' + base64.b64encode(archive.read(image_path)).decode('ascii')
    sheets = []
    for info in ET.fromstring(archive.read('xl/workbook.xml')).find('m:sheets', N):
        document = ET.fromstring(archive.read(resolve('xl', relations[info.attrib[REL + 'id']])))
        rows = []
        for row in document.findall('m:sheetData/m:row', N):
            cells = []
            for cell in row.findall('m:c', N):
                value = cell.findtext('m:v', default='', namespaces=N)
                if cell.attrib.get('t') == 's': value = strings[int(value)] if value else ''
                elif cell.attrib.get('t') == 'inlineStr': value = cell_text(cell)
                if not value or not value.strip(): continue
                item = {'ref': cell.attrib['r'], 'text': value}
                formula = cell.findtext('m:f', default='', namespaces=N)
                if formula: item['formula'] = formula
                image = re.search(r'DISPIMG\("([^"]+)"', formula or value)
                if image:
                    if image[1] not in images: raise ValueError('Unresolved image: ' + image[1])
                    item['imageId'] = image[1]
                cells.append(item)
            if cells: rows.append({'row': int(row.attrib['r']), 'cells': cells})
        sheets.append({'name': info.attrib['name'], 'rows': rows, 'merges': [cell.attrib['ref'] for cell in document.findall('m:mergeCells/m:mergeCell', N)]})
    naming_image = 'data:image/png;base64,' + base64.b64encode(archive.read('xl/media/image1.png')).decode('ascii')
    data = {'source': {'filename': SOURCE.name, 'sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(), 'importedAt': datetime.now(timezone.utc).isoformat(timespec='seconds'), 'worksheetCount': len(sheets)}, 'sheets': sheets, 'images': images, 'namingImage': naming_image}
    output = ROOT / 'src' / 'knowledge-data.js'
    output.write_text('// Generated by scripts/import-knowledge.py. Original cell text and cached values are preserved.\nexport const KNOWLEDGE_DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(json.dumps({'sheets': [{'name':s['name'], 'nonemptyRows':len(s['rows'])} for s in sheets], 'cellImages':len(images), 'output':str(output)}, ensure_ascii=False))
